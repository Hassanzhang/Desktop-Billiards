"""Generate the PyInstaller version resource (``version_info.txt``) for builds.

The release version has exactly one source of truth: ``dib/__init__.py``.
``build.ps1`` reads it and passes it here, so the version is never duplicated in
the spec file, in this script or in a committed generated file.

Usage:
    python tools/gen_version_info.py --version 0.1.0 --output build/version_info.txt
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

VERSION_RE = re.compile(r'^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$')

TEMPLATE = """# -*- coding: utf-8 -*-
# Generated by tools/gen_version_info.py for version {version}. Do not edit;
# run build.ps1 (or this script) again instead.
#
# For more details about fixed file info 'ffi' see:
# http://msdn.microsoft.com/en-us/library/ms646997.aspx
VSVersionInfo(
  ffi=FixedFileInfo(
    # filevers and prodvers should be always a tuple with four items: (1, 2, 3, 4)
    # Set not needed items to zero 0.
    filevers=({major}, {minor}, {patch}, 0),
    prodvers=({major}, {minor}, {patch}, 0),
    # Contains a bitmask that specifies the valid bits 'flags'
    mask=0x3f,
    # Contains a bitmask that specifies the Boolean attributes of the file.
    flags=0x0,
    # The operating system for which this file was designed.
    # 0x4 - NT and there is no need to change it.
    OS=0x40004,
    # The general type of file.
    # 0x1 - the file is an application.
    fileType=0x1,
    # The function of the file.
    # 0x0 - the function is not defined for this fileType
    subtype=0x0,
    # Creation date and time stamp.
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
      StringTable(
        '080404B0',
        [StringStruct('CompanyName', 'LXG'),
        StringStruct('FileDescription', '桌面图标台球'),
        StringStruct('FileVersion', '{version}'),
        StringStruct('InternalName', 'DesktopIconBilliards'),
        StringStruct('LegalCopyright', 'by LXG'),
        StringStruct('OriginalFilename', 'DesktopIconBilliards-{version}-win-x64.exe'),
        StringStruct('ProductName', '桌面图标台球'),
        StringStruct('ProductVersion', '{version}'),
        StringStruct('Comments', 'by LXG')])
      ]),
    VarFileInfo([VarStruct('Translation', [2052, 1200])])
  ]
)
"""


def parse_version(text: str) -> tuple[int, int, int]:
    """Split ``major.minor.patch`` into three integers, rejecting anything else."""
    match = VERSION_RE.match(text.strip())
    if match is None:
        raise ValueError(
            f"版本号格式无效: {text!r}；应为 major.minor.patch（如 0.1.0），"
            '来源为 dib/__init__.py 的 __version__。'
        )
    major, minor, patch = (int(part) for part in match.groups())
    return major, minor, patch


def build_version_info(version: str) -> str:
    major, minor, patch = parse_version(version)
    return TEMPLATE.format(
        version=version,
        major=major,
        minor=minor,
        patch=patch,
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description='Generate the PyInstaller VSVersionInfo resource file.'
    )
    parser.add_argument(
        '--version',
        required=True,
        help='release version in major.minor.patch form, e.g. 0.1.0',
    )
    parser.add_argument(
        '--output',
        required=True,
        type=Path,
        help='path of the version_info.txt file to write',
    )
    args = parser.parse_args(argv)

    version = args.version.strip()
    try:
        text = build_version_info(version)
    except ValueError as exc:
        print(f'错误: {exc}', file=sys.stderr)
        return 1

    output: Path = args.output
    try:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text, encoding='utf-8', newline='\n')
    except OSError as exc:
        print(f'错误: 无法写入版本信息文件 {output}: {exc}', file=sys.stderr)
        return 1

    print(f'已生成版本信息: {output} (version {version})')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
